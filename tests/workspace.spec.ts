import "dotenv/config";
import { test, expect } from "@playwright/test";
import { eq } from "drizzle-orm";
import { db, pool } from "@/db";
import { cases, savedPlaybooks } from "@/db/schema";

let createdId = "";
let initiallySaved = false;
const email = `clearsignal-check-${Date.now()}@example.com`;

test.describe.serial("ClearSignal support workflows", () => {
  test.afterAll(async () => {
    if (createdId) await db.delete(cases).where(eq(cases.id, createdId));
    if (initiallySaved) await db.insert(savedPlaybooks).values({ id: "broadband-basics" }).onConflictDoNothing();
    else await db.delete(savedPlaybooks).where(eq(savedPlaybooks.id, "broadband-basics"));
    await pool.end();
  });

  test("create, gather context, save progress, resolve, and export a case", async ({ page, request }) => {
    const errors: string[] = [];
    page.on("pageerror", error => errors.push(error.message));
    const original = await (await request.get("/api/workspace")).json();
    initiallySaved = original.savedPlaybooks.includes("broadband-basics");
    await page.goto("/");
    await expect(page.getByRole("heading", { name: "Good morning, Aisyah" })).toBeVisible();
    await page.getByRole("button", { name: "New case", exact: true }).click();
    await expect(page.getByRole("dialog")).toBeVisible();
    await page.getByLabel("Customer name").fill("Jordan Ellis");
    await page.getByLabel("Email address").fill(email);
    await page.getByLabel("What’s the issue?").fill("Broadband drops after a home move");
    await page.getByLabel("The customer’s story").fill("I moved home yesterday and my connection drops during work calls. I have restarted the router once and would like a stable connection.");
    await page.getByLabel("Service area").fill("Petaling Jaya, Selangor");
    const createdResponse = page.waitForResponse(response => response.url().endsWith("/api/cases") && response.request().method() === "POST");
    await page.getByRole("button", { name: "Create case", exact: true }).click();
    const created = await (await createdResponse).json();
    createdId = created.case.id;
    await expect(page.getByRole("dialog")).toContainText(createdId);
    await expect(page.getByText("There may be a bigger picture")).toBeVisible();
    await page.getByRole("tab", { name: /Conversation/ }).click();
    await expect(page.getByText("I moved home yesterday and my connection drops", { exact: false })).toBeVisible();
    await page.getByLabel("Internal note").fill("Verified the service address. The network incident may explain the drops. Follow up by email; do not repeat the router restart.");
    await page.getByRole("button", { name: "Save note", exact: true }).click();
    await expect(page.getByText("Verified the service address. The network incident may explain the drops. Follow up by email; do not repeat the router restart.", { exact: true })).toBeVisible();
    await page.getByRole("tab", { name: "The full picture" }).click();
    await page.getByText("Check for a network incident in the customer's area", { exact: true }).click();
    await expect(page.getByRole("checkbox").first()).toBeChecked();
    await expect(page.getByRole("combobox", { name: "Priority", exact: true })).toBeEnabled();
    await page.getByRole("combobox", { name: "Priority", exact: true }).selectOption("high");
    await expect(page.getByRole("combobox", { name: "Case owner", exact: true })).toBeEnabled();
    await page.getByRole("combobox", { name: "Case owner", exact: true }).selectOption("Faizal Rosli");
    await expect(page.getByRole("combobox", { name: "Status", exact: true })).toBeEnabled();
    await page.getByRole("combobox", { name: "Status", exact: true }).selectOption("in_progress");
    await expect(page.getByRole("button", { name: "Mark as resolved" })).toBeEnabled();
    await page.getByRole("button", { name: "A clearer customer update" }).click();
    await expect(page.getByLabel("Customer update draft")).toHaveValue(/Thanks for your patience/);
    const downloadPromise = page.waitForEvent("download");
    await page.getByRole("button", { name: "Export handoff" }).click();
    const download = await downloadPromise;
    expect(download.suggestedFilename()).toBe(`${createdId}-handoff.txt`);
    await page.getByRole("button", { name: "Mark as resolved" }).click();
    await expect(page.getByRole("button", { name: "Reopen case" })).toBeVisible();
    await page.reload();
    await page.keyboard.press("Control+k");
    await page.getByLabel("Search the workspace").fill(createdId);
    await page.getByRole("button", { name: new RegExp("Broadband drops after a home move") }).click();
    await expect(page.getByRole("combobox", { name: "Status", exact: true })).toHaveValue("resolved");
    await expect(page.getByRole("combobox", { name: "Priority", exact: true })).toHaveValue("high");
    await expect(page.getByRole("combobox", { name: "Case owner", exact: true })).toHaveValue("Faizal Rosli");
    await expect(page.getByRole("checkbox").first()).toBeChecked();
    const stored = await (await request.get(`/api/cases/${createdId}`)).json();
    expect(stored.notes.some((note: { content: string }) => note.content.startsWith("Verified the service address."))).toBeTruthy();
    expect(stored.case.completedSteps).toContain("0");
    expect(stored.case.status).toBe("resolved");
    await page.getByRole("button", { name: "Close dialog" }).click();
    await page.locator(".nav-item").filter({ hasText: "Playbooks" }).click();
    const bookmark = page.locator(".playbook-card").filter({ hasText: "Bring broadband back online" }).getByRole("button", { name: /save Bring broadband back online/i });
    await bookmark.click();
    await expect(bookmark).toHaveAttribute("aria-label", initiallySaved ? "Save Bring broadband back online" : "Unsave Bring broadband back online");
    await page.reload();
    await expect(page.locator(".playbook-card").filter({ hasText: "Bring broadband back online" }).getByRole("button", { name: initiallySaved ? "Save Bring broadband back online" : "Unsave Bring broadband back online", exact: true })).toBeVisible();
    await page.locator(".nav-item").filter({ hasText: "Network status" }).click();
    await page.getByRole("button", { name: /Intermittent fibre connectivity/ }).click();
    await expect(page.getByRole("dialog")).toContainText("Sarah Chen");
    await page.getByRole("button", { name: "View area’s cases" }).click();
    await expect(page.getByLabel("Search cases")).toHaveValue("Petaling Jaya");
    await expect(page.locator(".case-table tbody tr")).toHaveCount(2);
    await page.locator(".nav-item").filter({ hasText: "Insights" }).click();
    const reportPromise = page.waitForEvent("download");
    await page.getByRole("button", { name: "Export report" }).click();
    expect((await reportPromise).suggestedFilename()).toMatch(/clearsignal-cases.*\.csv$/);
    const invalid = await request.post("/api/cases", { data: { customerName: "Missing details" } });
    expect(invalid.status()).toBe(400);
    expect(errors).toEqual([]);
  });

  test("mobile navigation, layout, and direct guide links work", async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto("/");
    await expect(page.getByRole("heading", { name: "Good morning, Aisyah" })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
    await page.getByRole("button", { name: "Open navigation" }).click();
    await page.locator(".nav-item").filter({ hasText: "Customers" }).click();
    await expect(page.getByRole("heading", { name: "People, not just account numbers." })).toBeVisible();
    await page.getByLabel("Search customers").fill("Sarah");
    await expect(page.locator(".customer-card")).toHaveCount(1);
    await page.locator(".customer-card").click();
    await expect(page.getByRole("dialog")).toContainText("Sarah Chen");
    await page.getByRole("button", { name: "Close dialog" }).click();
    await page.goto("/?view=playbooks&q=mobile-data");
    await expect(page.getByRole("dialog")).toContainText("Get mobile data moving");
    await page.getByRole("button", { name: "Close dialog" }).click();
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  });
});
